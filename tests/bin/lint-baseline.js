#!/usr/bin/env node
/**
 * Lint ratchet — fail on new lint findings, tolerate the recorded ones.
 *
 * ESLint 8, Stylelint 16 and markdownlint-cli have no suppressions file, so
 * this records each linter's findings as counts per file and rule in
 * tests/baselines/<linter>.json and compares every run against it:
 *
 * - a count above its baseline fails — that is a new finding;
 * - a count below its baseline fails too, until the baseline is regenerated —
 *   so a fix shrinks the baseline in the same PR and the debt cannot regrow.
 *
 * Each linter runs through its own `npm run lint:*` script, so config and
 * ignore files are exactly the ones `npm run lint` uses.
 *
 *   npm run lint:baseline                    # check every linter
 *   npm run lint:baseline -- eslint          # check one
 *   npm run lint:baseline:update             # regenerate after a fix
 *
 * Deliberately a twin of the same file in the companion repo.
 *
 * @package SD_Theme_2026
 * @subpackage Tests
 */

const { spawnSync } = require( 'child_process' );
const fs = require( 'fs' );
const os = require( 'os' );
const path = require( 'path' );

const ROOT = path.join( __dirname, '..', '..' );

/**
 * How to run each linter and read its JSON report into `{ file, rule }` rows.
 * Errors only: warnings do not fail `npm run lint` either.
 */
const LINTERS = {
	eslint: {
		script: 'lint:js',
		args: ( out ) => [ '--format=json', `--output-file=${ out }` ],
		parse: ( report ) =>
			report.flatMap( ( result ) =>
				result.messages
					.filter( ( message ) => 2 === message.severity )
					.map( ( message ) => ( {
						file: result.filePath,
						rule: message.ruleId || 'parse-error',
					} ) )
			),
	},
	stylelint: {
		script: 'lint:css',
		args: ( out ) => [ '--formatter=json', `--output-file=${ out }` ],
		parse: ( report ) =>
			report.flatMap( ( result ) =>
				result.warnings
					.filter( ( warning ) => 'error' === warning.severity )
					.map( ( warning ) => ( {
						file: result.source,
						rule: warning.rule,
					} ) )
			),
	},
	markdownlint: {
		script: 'lint:md',
		args: ( out ) => [ '--json', `--output=${ out }` ],
		parse: ( report ) =>
			report.map( ( finding ) => ( {
				file: finding.fileName,
				rule: finding.ruleNames[ 0 ],
			} ) ),
	},
};

class LintBaseline {
	/**
	 * @param {string} name   Key in LINTERS.
	 * @param {Object} linter Its entry.
	 */
	constructor( name, linter ) {
		this.name = name;
		this.linter = linter;
		this.file = path.join( ROOT, 'tests', 'baselines', `${ name }.json` );
	}

	/**
	 * Run the linter and count its errors per file and rule.
	 *
	 * @return {Object<string, Object<string, number>>} Counts, keys sorted.
	 */
	measure() {
		const out = path.join(
			fs.mkdtempSync( path.join( os.tmpdir(), 'lint-baseline-' ) ),
			`${ this.name }.json`
		);

		// Stylelint echoes its report to stderr as well, so stderr is shown
		// only when the run produced no report — i.e. the linter itself broke.
		const run = spawnSync(
			'npm',
			[
				'run',
				'-s',
				this.linter.script,
				'--',
				...this.linter.args( out ),
			],
			{ cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
		);

		if ( ! fs.existsSync( out ) ) {
			throw new Error(
				`${ this.name }: \`npm run ${
					this.linter.script
				}\` wrote no report.\n${ run.stderr.slice( -2000 ) }`
			);
		}

		const raw = fs.readFileSync( out, 'utf8' ).trim();
		const counts = {};

		for ( const { file, rule } of this.linter.parse(
			raw ? JSON.parse( raw ) : []
		) ) {
			const relative = path
				.relative( ROOT, path.resolve( ROOT, file ) )
				.split( path.sep )
				.join( '/' );
			counts[ relative ] ??= {};
			counts[ relative ][ rule ] =
				( counts[ relative ][ rule ] ?? 0 ) + 1;
		}

		return LintBaseline.sorted( counts );
	}

	/**
	 * @return {Object<string, Object<string, number>>} Recorded counts.
	 */
	recorded() {
		return fs.existsSync( this.file )
			? JSON.parse( fs.readFileSync( this.file, 'utf8' ) ).findings
			: {};
	}

	/**
	 * @param {Object} counts Counts from measure().
	 */
	write( counts ) {
		const total = Object.values( counts ).reduce(
			( sum, rules ) =>
				sum + Object.values( rules ).reduce( ( a, b ) => a + b, 0 ),
			0
		);
		fs.mkdirSync( path.dirname( this.file ), { recursive: true } );
		fs.writeFileSync(
			this.file,
			JSON.stringify(
				{
					$comment: `Generated by tests/bin/lint-baseline.js — do not edit by hand. ${ total } recorded ${ this.name } errors; the number may only go down.`,
					findings: counts,
				},
				null,
				'\t'
			) + '\n'
		);
	}

	/**
	 * Compare a measurement with the baseline.
	 *
	 * @param {Object} counts Counts from measure().
	 * @return {{added: string[], fixed: string[]}} Differences, one line each.
	 */
	compare( counts ) {
		const baseline = this.recorded();
		const added = [];
		const fixed = [];
		const files = new Set( [
			...Object.keys( counts ),
			...Object.keys( baseline ),
		] );

		for ( const file of [ ...files ].sort() ) {
			const now = counts[ file ] ?? {};
			const before = baseline[ file ] ?? {};

			for ( const rule of new Set( [
				...Object.keys( now ),
				...Object.keys( before ),
			] ) ) {
				const delta = ( now[ rule ] ?? 0 ) - ( before[ rule ] ?? 0 );

				if ( delta > 0 ) {
					added.push( `  + ${ file }  ${ rule }  (+${ delta })` );
				} else if ( delta < 0 ) {
					fixed.push( `  - ${ file }  ${ rule }  (${ delta })` );
				}
			}
		}

		return { added, fixed };
	}

	/**
	 * @param {Object} obj Nested counts.
	 * @return {Object} Same counts with keys sorted, for stable diffs.
	 */
	static sorted( obj ) {
		return Object.fromEntries(
			Object.keys( obj )
				.sort()
				.map( ( key ) => [
					key,
					'object' === typeof obj[ key ]
						? LintBaseline.sorted( obj[ key ] )
						: obj[ key ],
				] )
		);
	}
}

const argv = process.argv.slice( 2 );
const update = argv.includes( '--update' );
const names = argv.filter( ( arg ) => ! arg.startsWith( '--' ) );
let failed = false;

for ( const name of names.length ? names : Object.keys( LINTERS ) ) {
	if ( ! LINTERS[ name ] ) {
		throw new Error(
			`Unknown linter "${ name }". Known: ${ Object.keys( LINTERS ).join(
				', '
			) }.`
		);
	}

	const baseline = new LintBaseline( name, LINTERS[ name ] );
	const counts = baseline.measure();

	if ( update ) {
		baseline.write( counts );
		process.stdout.write( `${ name }: baseline written.\n` );
		continue;
	}

	const { added, fixed } = baseline.compare( counts );

	if ( added.length ) {
		failed = true;
		process.stdout.write(
			`${ name }: new errors not in the baseline — fix them:\n${ added.join(
				'\n'
			) }\n`
		);
	}

	if ( fixed.length ) {
		failed = true;
		process.stdout.write(
			`${ name }: errors fixed — shrink the baseline in this PR with \`npm run lint:baseline:update\`:\n${ fixed.join(
				'\n'
			) }\n`
		);
	}

	if ( ! added.length && ! fixed.length ) {
		process.stdout.write( `${ name }: matches the baseline.\n` );
	}
}

process.exitCode = failed ? 1 : 0;
